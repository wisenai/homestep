#!/usr/bin/env python3
"""Check that requirements and tests point at each other, and write
docs/traceability.md.

Requirements are `### REQ-AREA-NN Title` headings in docs/requirements.md,
each with a `**Verified by:**` line. Tests cite them in a comment such as
`// REQ-STEP-03` (Swift) or `# REQ-LOG-04` (Python). Field protocols cite
them in docs/testing/field-protocols.md.

Fails (exit 1) when:
  * a requirement verified by unit, scenario, ui or check has no test or check citing it,
  * a requirement verified by field has no field protocol citing it,
  * a test cites a requirement that doesn't exist.

Usage: tools/trace.py [--write]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REQS = ROOT / "docs" / "requirements.md"
OUT = ROOT / "docs" / "traceability.md"
TEST_DIRS = ["Core/Tests", "Tests", "UITests", "tools/tests"]
CHECKS = ["tools/check.py"]
FIELD = ROOT / "docs" / "testing" / "field-protocols.md"
AUTOMATED = {"unit", "scenario", "ui", "check"}
ID = re.compile(r"REQ-[A-Z]+-\d+")


def load_requirements():
    reqs, current = {}, None
    for line in REQS.read_text().splitlines():
        m = re.match(r"### (REQ-[A-Z]+-\d+) (.+)", line)
        if m:
            current = m.group(1)
            reqs[current] = {"title": m.group(2), "methods": set(), "open": False}
        elif current and line.startswith("- **Verified by:**"):
            reqs[current]["methods"] = {w.strip() for w in line.split(":**", 1)[1].split(",")}
        elif current and line.startswith("- **Status:**") and "open" in line:
            reqs[current]["open"] = True
    return reqs


def citations(paths):
    found = {}
    for base in paths:
        p = ROOT / base
        files = [p] if p.is_file() else sorted(p.rglob("*")) if p.exists() else []
        for f in files:
            if f.suffix not in {".swift", ".py"} or "fixtures" in f.parts:
                continue
            for line in f.read_text().splitlines():
                for i in ID.findall(line):
                    found.setdefault(i, []).append(f"{f.relative_to(ROOT)}")
    return {k: sorted(set(v)) for k, v in found.items()}


def main():
    reqs = load_requirements()
    tests = citations(TEST_DIRS)
    checks = citations(CHECKS)
    field = set(ID.findall(FIELD.read_text())) if FIELD.exists() else set()

    problems = []
    for rid in sorted(set(tests) | set(checks)):
        if rid not in reqs:
            problems.append(f"{rid} is cited by {', '.join(tests.get(rid, checks.get(rid, [])))} but not defined")
    rows = []
    for rid, r in reqs.items():
        by = tests.get(rid, []) + checks.get(rid, [])
        methods = r["methods"]
        if not methods:
            problems.append(f"{rid} has no 'Verified by' line")
        if methods & AUTOMATED and not by:
            problems.append(f"{rid} ({', '.join(sorted(methods))}) has no test or check")
        if "field" in methods and rid not in field:
            problems.append(f"{rid} is verified in the field but no protocol in field-protocols.md cites it")
        where = [f"`{b}`" for b in by]
        if "field" in methods:
            where.append("field protocol")
        if "inspection" in methods:
            where.append("inspection")
        status = "open (known issue)" if r["open"] else ("traced" if where else "untraced")
        rows.append(f"| {rid} | {r['title']} | {', '.join(sorted(methods))} | {'<br>'.join(where)} | {status} |")

    if "--write" in sys.argv:
        OUT.write_text(
            "# Traceability\n\n"
            "Generated by `tools/trace.py --write`; don't edit by hand. Each requirement in "
            "[`requirements.md`](requirements.md), how it is verified, and where.\n\n"
            f"{len(reqs)} requirements; {sum(1 for r in reqs.values() if r['open'])} open.\n\n"
            "| Requirement | Title | Verified by | Where | Status |\n|---|---|---|---|---|\n"
            + "\n".join(rows) + "\n")

    for p in problems:
        print("trace:", p)
    print(f"trace: {len(reqs)} requirements, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
